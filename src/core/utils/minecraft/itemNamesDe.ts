export const ITEM_NAMES_DE: Readonly<Record<string, string>> = { ...coloredNames(), ...NAMES };

const titleCase = (words: string): string =>
  words.replace(/_/g, " ").replace(/\b\w/g, (char) => char.toUpperCase());

/** The German name of a vanilla item id without namespace, or undefined when it is not drafted. */
export function germanItemName(id: string): string | undefined {
  const direct = ITEM_NAMES_DE[id];
  if (direct) return direct;
  const disc = /^music_disc_(.+)$/.exec(id);
  if (disc) return `Schallplatte ${titleCase(disc[1]!)}`;
  const fragment = /^disc_fragment_(\d+)$/.exec(id);
  if (fragment) return `Plattenfragment ${fragment[1]}`;
  return undefined;
}
