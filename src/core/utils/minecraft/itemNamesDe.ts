/**
 * German item names for the ids the daily reward pool uses.
 *
 * Drafted by hand and not yet reviewed by a native speaker. An id that is not
 * here shows its English name, which is better than a wrong German one: pottery
 * sherds, banner patterns, armor trims and a few newer items are left out on
 * purpose until someone confirms the game's own wording.
 */

/** Adjective stem per dye color, and whether the stem takes an ending. */
const COLORS: ReadonlyArray<readonly [id: string, stem: string, declines: boolean]> = [
  ["white", "Weiß", true],
  ["orange", "Orangefarben", true],
  ["magenta", "Magentafarben", true],
  ["light_blue", "Hellblau", true],
  ["yellow", "Gelb", true],
  ["lime", "Hellgrün", true],
  ["pink", "Rosa", false],
  ["gray", "Grau", true],
  ["light_gray", "Hellgrau", true],
  ["cyan", "Türkis", true],
  ["purple", "Violett", true],
  ["blue", "Blau", true],
  ["brown", "Braun", true],
  ["green", "Grün", true],
  ["red", "Rot", true],
  ["black", "Schwarz", true],
];

/** The ending follows the noun's gender: Wolle and Terrakotta take "e", Beton "er", Buntglas "es". */
const COLORED: ReadonlyArray<readonly [family: string, ending: string, noun: string]> = [
  ["wool", "e", "Wolle"],
  ["terracotta", "e", "Terrakotta"],
  ["glazed_terracotta", "e", "glasierte Terrakotta"],
  ["concrete", "er", "Beton"],
  ["stained_glass", "es", "Buntglas"],
];

function coloredNames(): Record<string, string> {
  const names: Record<string, string> = {};
  for (const [color, stem, declines] of COLORS) {
    for (const [family, ending, noun] of COLORED) {
      names[`${color}_${family}`] = `${declines ? stem + ending : stem} ${noun}`;
    }
  }
  return names;
}

