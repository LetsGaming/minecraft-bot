/**
 * Vendor the wrapper's OpenAPI document and generate the wire types from it.
 *
 * The wrapper (mc-api-server) generates openapi.json from its router; this
 * script copies that file to src/schema/wire/openapi.json and turns it into
 * src/schema/wire/types.ts with openapi-typescript. Both outputs are
 * committed, so a build never needs the wrapper checkout.
 *
 *   npm run wire:sync -- <wrapper dir>     (or WRAPPER_DIR=<dir>)
 *   npm run wire:check                     fails when the committed files are stale
 *
 * wire:check always verifies that types.ts is exactly what the vendored
 * openapi.json generates. With a wrapper dir it also verifies that the
 * vendored file is the wrapper's current one; CI passes the dir, a local run
 * without it checks the first half only. That comparison ignores info.version:
 * it is the wrapper's package version, which every release moves without the
 * HTTP surface changing, and the types never contain it.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "fs";
import path from "path";
import { fileURLToPath } from "url";
import openapiTS, { astToString } from "openapi-typescript";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const wireDir = path.join(root, "src/schema/wire");
const vendoredPath = path.join(wireDir, "openapi.json");
const typesPath = path.join(wireDir, "types.ts");

const HEADER = `/**
 * Wire types for the wrapper's HTTP API. Generated by scripts/sync-wire.mjs
 * from the vendored openapi.json next to this file. Do not edit by hand:
 * change the wrapper's route schemas and run \`npm run wire:sync\`.
 */
// prettier-ignore
`;

const args = process.argv.slice(2);
const check = args.includes("--check");
const explicitDir = args.find((a) => !a.startsWith("--"));
const wrapperDir = explicitDir ?? process.env.WRAPPER_DIR;

function readNormalized(file) {
  return readFileSync(file, "utf-8").replace(/\r\n/g, "\n");
}

function fail(message) {
  console.error(message);
  process.exit(1);
}

/** The document with info.version blanked, for comparing the HTTP surface. */
function withoutVersion(specText) {
  const spec = JSON.parse(specText);
  if (spec.info) delete spec.info.version;
  return JSON.stringify(spec);
}

function resolveWrapperSpec() {
  if (!wrapperDir) return null;
  const file = path.join(path.resolve(wrapperDir), "openapi.json");
  if (!existsSync(file)) {
    fail(
      `No openapi.json in ${path.resolve(wrapperDir)}.\n` +
        "Build the wrapper checkout first (npm run openapi:generate there), or point at one that has it.",
    );
  }
  return readNormalized(file);
}

async function generateTypes(specText) {
  const ast = await openapiTS(JSON.parse(specText), { alphabetize: true });
  return HEADER + astToString(ast);
}

if (check) {
  if (!existsSync(vendoredPath) || !existsSync(typesPath)) {
    fail("src/schema/wire is missing. Run `npm run wire:sync -- <wrapper dir>`.");
  }
  const vendored = readNormalized(vendoredPath);
  const wrapperSpec = resolveWrapperSpec();
  if (wrapperSpec !== null && withoutVersion(wrapperSpec) !== withoutVersion(vendored)) {
    fail(
      "src/schema/wire/openapi.json differs from the wrapper's openapi.json.\n" +
        "Run `npm run wire:sync -- <wrapper dir>` and commit the result.",
    );
  }
  if ((await generateTypes(vendored)) !== readNormalized(typesPath)) {
    fail(
      "src/schema/wire/types.ts is out of date with openapi.json.\n" +
        "Run `npm run wire:sync` and commit the result.",
    );
  }
  console.log(
    wrapperSpec === null
      ? "Wire types match the vendored openapi.json (wrapper not provided, vendored copy not compared)."
      : "Wire types and vendored openapi.json are up to date.",
  );
} else {
  const spec = resolveWrapperSpec();
  if (spec === null) {
    fail(
      "Usage: npm run wire:sync -- <wrapper dir>\n" +
        "   or: WRAPPER_DIR=<wrapper dir> npm run wire:sync\n" +
        "The directory must contain the wrapper's generated openapi.json.",
    );
  }
  mkdirSync(wireDir, { recursive: true });
  writeFileSync(vendoredPath, spec);
  writeFileSync(typesPath, await generateTypes(spec));
  console.log(
    `Wrote ${path.relative(root, vendoredPath)} and ${path.relative(root, typesPath)}`,
  );
}
